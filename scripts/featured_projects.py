#!/usr/bin/env python3
"""Rank public repositories and render the "Featured Projects" section of README.md.

Every public, non-fork, non-archived repository gets a score from 0 to 100:

    recency        20  last push, decays linearly to 0 over 540 days
    commits        25  log-scaled, 60+ commits = full marks
    codebase size  15  log-scaled bytes of source code (binaries/zips ignored)
    documentation  25  real README (not a framework template) 12,
                       description 6, topics 4, homepage 3
    community      10  stars and forks, 5 points each (capped)
    license         5  has a license file

Repos in `pinned` are always featured first; repos in `exclude` never appear.
Card text comes from `.github/featured-projects.json` when present, otherwise
from the repository description.

Usage:
    python scripts/featured_projects.py                 # update README.md
    python scripts/featured_projects.py --dry-run       # print ranking only
    python scripts/featured_projects.py --fixture f.json
    python scripts/featured_projects.py --sync-metadata # push descriptions/topics
"""
